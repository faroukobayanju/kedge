"""Build the static landing page: copy the replay engine and bake real run data into site/.

Usage: uv run python scripts/build_site.py <no-guard run_id> <kedge run_id>
"""
import json
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from kedge import server  # noqa: E402

UI = os.path.join(ROOT, "kedge", "ui")
SITE = os.path.join(ROOT, "site")
# fields the page reads; everything else (local paths, plan prompts) stays off the public site
KEEP = ("run_id", "pr_url", "title", "repo", "status", "guard", "storm", "cost_usd_total", "rollbacks", "drifts",
        "false_claims", "draft_pr", "trace", "ci_status", "base_total", "plan", "steps", "entire_explain")


def main(ids):
    runs_dir = os.path.join(ROOT, "runs")
    data = []
    for i in ids:
        r = server.run_detail(runs_dir, i)
        if not r:
            sys.exit(f"run {i} not found in runs/")
        data.append({k: r.get(k) for k in KEEP})
    for f in ("app.js", "app.css", "fonts2.css"):
        shutil.copy(os.path.join(UI, f), os.path.join(SITE, f))
    shutil.copytree(os.path.join(UI, "fonts"), os.path.join(SITE, "fonts"), dirs_exist_ok=True)
    blob = json.dumps({"data": data, "race": ids})
    # keep machine paths (and the username inside them) off the public page
    blob = re.sub(r"(/private)?/var/folders/[^\"'\\ ]+?/T/kedge/[\w-]+", "<run-clone>", blob)
    blob = blob.replace(os.path.expanduser("~"), "~")
    with open(os.path.join(SITE, "data.js"), "w") as f:
        f.write("// generated by scripts/build_site.py from real Kedge runs\n")
        f.write(f"window.KEDGE = {blob};\n")
    print(f"site/ built with runs {', '.join(ids)}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1:])
